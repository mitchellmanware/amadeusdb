################################################################################
#' Discover source files by filename pattern and date range
#'
#' @description
#' Search input directories recursively for filenames matching a regular
#' expression, then retain paths containing a date in the requested range.
#'
#' @param date character(2). Inclusive start and end dates in chronological
#'   order, formatted as `"YYYY-MM-DD"`. Only the first two elements are used.
#'   Repeat the same date to search one day; a single date is not expanded.
#' @param input character. Directory path or paths to search recursively.
#'   Passed to [base::list.files()] without normalization or existence checks.
#' @param pattern character(1). Regular expression used by [base::list.files()]
#'   to select filenames. Matching is case-sensitive.
#' @param sub_hyphen logical(1). Whether to remove hyphens from the generated
#'   date strings before matching paths. Defaults to `TRUE`, matching dates
#'   such as `"20240101"`. Use `FALSE` to match `"2024-01-01"` instead.
#'
#' @details
#' The date sequence is generated by [amadeus::generate_date_sequence()].
#' Dates are combined into a regular expression and matched against the full
#' returned paths, including directory names. Matching uses date text rather
#' than file contents, file modification times, or parsed source metadata.
#'
#' Repeated path strings are removed, preserving the order returned by
#' [base::list.files()]. Hidden files and directories are excluded according
#' to that function's defaults. No additional argument validation is performed.
#'
#' @return
#' A character vector of unique matching file paths, or `character(0)` when
#' no files match. Paths include their input directory prefix but are not
#' normalized to absolute paths.
#'
#' @importFrom amadeus generate_date_sequence
#' @seealso [sedona_geos()], [amadeus::generate_date_sequence()],
#'   [base::list.files()]
#' @keywords internal
#' @examples
#' \dontrun{
#' geos_files <- discover(
#'   date = c("2024-01-01", "2024-01-02"),
#'   input = "data/geos",
#'   pattern = "^GEOS-CF",
#'   sub_hyphen = TRUE
#' )
#' }
#' @export
discover <- function(
  date,
  input,
  pattern,
  sub_hyphen = TRUE
) {
  # ----------------------------------------------------------------------------
  # Identify file paths from all files in the path.
  chr_paths <- list.files(
    input,
    pattern = pattern,
    full.names = TRUE,
    recursive = TRUE
  )
  # ----------------------------------------------------------------------------
  # Generate sequence from user supplied dates.
  chr_datesofinterest <- amadeus::generate_date_sequence(
    date[1],
    date[2],
    sub_hyphen = sub_hyphen
  )
  # ----------------------------------------------------------------------------
  # Select only those file paths which align with user supplied date sequence.
  unique(
    grep(
      paste(
        chr_datesofinterest,
        collapse = "|"
      ),
      chr_paths,
      value = TRUE
    )
  )
}
